const allowed = new Set<string>(TRANSLATION_UI_KEYS)
let strings: Record<string, string> = {}
export function configureTranslationUi(value: unknown): void {
  strings = {}
  if (!value || typeof value !== "object" || Array.isArray(value)) return
  for (const [key, text] of Object.entries(value))
    if (allowed.has(key) && typeof text === "string" && text.length <= 2048) strings[key] = text
}
export function ui(message: string, params: Record<string, string | number> = {}): string {
  if (!allowed.has(message)) return message
  const text = strings[message] ?? message
  return text.replace(/\{(\w+)\}/gu, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  )
}
